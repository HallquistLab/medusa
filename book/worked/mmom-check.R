source_dir <- Sys.getenv("MEDUSA_SOURCE")
if (nzchar(source_dir)) pkgload::load_all(source_dir, compile = TRUE, quiet = TRUE)
library(medusa)
ar <- c(.60, .12, -.24)
phi <- c(ar[1] + ar[2], ar[3] - ar[1] * ar[2], -ar[1] * ar[3])
reference <- toeplitz(as.numeric(stats::ARMAacf(ar = phi, lag.max = 79)))
got <- medusa:::compute_ar1_operator_cov(diag(80), 1:80, ar, center_obs = FALSE)
covariance_check <- max(abs(got - reference))
stopifnot(covariance_check < 1e-10)
set.seed(20261110)
n <- 300L
latent <- rnorm(n)
task <- rnorm(n)
se <- runif(n, .3, .7)
X <- cbind(neural = latent + rnorm(n, sd = se), task = task)
Psi <- array(0, dim = c(2L, 2L, n))
Psi[1, 1, ] <- se^2
outcome <- .6 * latent + .25 * task + rnorm(n, sd = .8)
fit <- medusa_fit_mmom(outcome, X, Psi, regularization = "step_up")
stopifnot(isTRUE(fit$converged), all(is.finite(fit$coefficients$se)), all(fit$coefficients$se > 0))
saveRDS(list(covariance_check = covariance_check, coefficients = fit$coefficients), "mmom-check.rds")
