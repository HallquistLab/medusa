# Reproducible, illustrative examples generated with live library(medusa).
library(medusa)
library(ggplot2)
set.seed(1101026)

tr <- 0.65
n <- 360L
tt <- (0:(n - 1L)) * tr

# Default recommended 3D physiological manifold (delay x dispersion x undershoot_ratio, positive-lobe normalized)
K_medusa <- hrf_library(tr, preset = "medusa")
pars_medusa <- attr(K_medusa, "parameters")

# 2D fixed-undershoot slice (canonical_27) used for clean 2D delay x dispersion heatmap visualization
K <- hrf_library(tr, preset = "canonical_27")
pars <- attr(K, "parameters")
idx <- function(d, s) which(pars$peak_delay == d & pars$dispersion == s)
true_idx <- c(Fast = idx(4.5, 0.9), Slow = idx(7.5, 1.1), Null = 1L)

ids <- sprintf("v%02d", 1:24)
groups <- setNames(rep(names(true_idx), each = 8L), ids)
sd_vox <- rep(seq(0.012, 0.055, length.out = 8L), 3L)
phi <- c(0.65 + 0.2, -0.3 - 0.65 * 0.2, -0.65 * (-0.3))

# Event design matches package timing conventions. AR(3) errors generated by stats::arima.sim.
bold <- events <- nuisance <- errors <- amplitudes <- list()
for (r in 1:3) {
  rn <- paste0("run", r)
  ev <- data.frame(onset = 8 + cumsum(c(0, runif(23, 7.2, 8.2))), condition = "event", duration = 0)
  X <- medusa:::hrf_event_design_cpp(n, tr, 0, ev$onset, ev$duration, 1:24, 24L, K)
  z <- cbind(
    dct1 = cos(pi * (2 * (0:(n - 1L)) + 1) / (2 * n)),
    dct2 = cos(pi * (2 * (0:(n - 1L)) + 1) * 2 / (2 * n))
  )
  a <- 1.4 + 0.85 * rnorm(24)
  Y <- E <- matrix(0, n, 24L, dimnames = list(NULL, ids))
  for (v in 1:24) {
    e <- as.numeric(arima.sim(list(ar = phi), n = n, n.start = 1000))
    gamma0 <- 1 / (1 - sum(phi * as.numeric(ARMAacf(ar = phi, lag.max = 3))[-1]))
    e <- e / sqrt(gamma0) * sd_vox[v]
    gain <- if (v %% 2 == 0) -1 else 1
    signal <- if (groups[v] == "Null") rep(0, n) else as.numeric(X[[true_idx[groups[v]]]] %*% (gain * a))
    Y[, v] <- signal + 0.035 * z[, 1] + 0.015 * z[, 2] + e
    E[, v] <- e
  }
  bold[[rn]] <- Y
  events[[rn]] <- ev
  nuisance[[rn]] <- z
  errors[[rn]] <- E
  amplitudes[[rn]] <- a
}

fitfun <- function(y = bold, ev = events, nu = nuisance, kg = K, ...) {
  estimate_crossrun_hrf(
    bold = y, events = ev, tr = tr, kernel_grid = kg, nuisance = nu,
    spatial_groups = groups, amplitude_model = "trial", return_scores = TRUE, ...
  )
}

message("Main parcel soft fit (recommended)")
soft <- fitfun(pooling = "parcel", selection_mode = "soft_average")

message("Hard and voxel fits")
hard <- fitfun(pooling = "parcel", selection_mode = "hard")
voxel <- fitfun(pooling = "voxel", selection_mode = "hard")

message("Fixed canonical HRF comparator (misspecified delay in Fast/Slow)")
canonical_only <- fitfun(kg = K[, 1L, drop = FALSE], pooling = "parcel", selection_mode = "hard")

message("Target-perturbation cross-fitting invariance check")
altered <- bold
altered$run1 <- altered$run1 + outer(sin(tt / 2) + 0.4 * sin(tt / 0.8), seq(0.08, 0.3, length.out = 24L))
perturbed <- fitfun(y = altered, pooling = "parcel", selection_mode = "soft_average")
weight_difference <- max(abs(soft$kernel_weights$run1 - perturbed$kernel_weights$run1))
kernel_difference <- max(abs(soft$selected_kernels$run1 - perturbed$selected_kernels$run1))
stopifnot(weight_difference == 0, kernel_difference == 0)

message("Signed trial amplitudes example")
signed_y <- list()
signed_events <- events
for (r in 1:3) {
  ev <- events[[r]]
  X <- medusa:::hrf_event_design_cpp(n, tr, 0, ev$onset, ev$duration, 1:24, 24L, K)[[idx(7.5, 1.1)]]
  a <- rep(c(-1, 1), 12L) * runif(24L, 1.0, 2.0)
  Y <- sapply(1:8, function(v) as.numeric(X %*% a) + as.numeric(arima.sim(list(ar = 0.4), n = n)) * 0.012)
  colnames(Y) <- ids[1:8]
  signed_y[[r]] <- Y
}
names(signed_y) <- names(events)
signedfit <- function(mode) {
  estimate_crossrun_hrf(
    bold = signed_y, events = signed_events, tr = tr, kernel_grid = K,
    spatial_groups = setNames(rep("Signed", 8L), ids[1:8]),
    amplitude_model = mode, pooling = "parcel", selection_mode = "soft_average", return_scores = TRUE
  )
}
signed_condition <- signedfit("condition")
signed_trial <- signedfit("trial")

# Known-error whitening check: post-selection AR(p) refit vs misspecified fixed canonical HRF
rows <- 1:n
ar_cols <- intersect(c("rho", "psi1", "psi2", "psi3", "psi4"), names(soft$noise$run1))
arhat_soft <- unlist(soft$noise$run1[1L, ar_cols], use.names = FALSE)
arhat_can <- unlist(canonical_only$noise$run1[1L, ar_cols], use.names = FALSE)
raw_error <- errors$run1[, 1:8, drop = FALSE]
wc_soft <- medusa:::hrf_whitening_matrix(rows, arhat_soft)
wc_can <- medusa:::hrf_whitening_matrix(rows, arhat_can)
acfmean <- function(m) rowMeans(sapply(1:ncol(m), function(v) as.numeric(acf(m[, v], lag.max = 16, plot = FALSE)$acf)))
acf_df <- rbind(
  data.frame(lag = 0:16, acf = acfmean(raw_error), series = "Simulated BOLD error"),
  data.frame(lag = 0:16, acf = acfmean(wc_can %*% raw_error), series = "Fixed canonical HRF noise fit"),
  data.frame(lag = 0:16, acf = acfmean(wc_soft %*% raw_error), series = "MEDuSA post-selection AR(p) refit")
)

sel <- do.call(rbind, lapply(names(soft$selections), function(r) {
  d <- soft$selections[[r]]
  d$run <- r
  d
}))
write.csv(sel, "selections.csv", row.names = FALSE)

noise <- do.call(rbind, lapply(names(soft$noise), function(r) {
  d <- soft$noise[[r]]
  d$run <- r
  d
}))
write.csv(noise, "noise.csv", row.names = FALSE)

saveRDS(
  list(
    tr = tr, n = n, tt = tt, K = K, pars = pars, K_medusa = K_medusa, pars_medusa = pars_medusa,
    true_idx = true_idx, ids = ids, groups = groups, sd_vox = sd_vox, phi = phi,
    bold = bold, events = events, nuisance = nuisance, errors = errors, amplitudes = amplitudes,
    soft = soft, hard = hard, voxel = voxel, canonical_only = canonical_only, perturbed = perturbed,
    signed_condition = signed_condition, signed_trial = signed_trial, signed_y = signed_y,
    acf_df = acf_df, weight_difference = weight_difference, kernel_difference = kernel_difference
  ),
  "step1_examples.rds"
)
writeLines(capture.output(sessionInfo()), "sessionInfo.txt")
message("Step 1 examples saved")
